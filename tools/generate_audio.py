VOICE = "ar-EG-ShakirNeural"
RATE = "-10%"
BASE = pathlib.Path("D:/New folder (11)/adhkar/assets/audio")

async def gen_one(text, out):
    out.parent.mkdir(parents=True, exist_ok=True)
    c = edge_tts.Communicate(text, VOICE, rate=RATE)
    await c.save(str(out))
    print(f"OK {out.name} {out.stat().st_size//1024}KB")

async def main():
    for i, t in enumerate(morning, 1):
        out = BASE / f"morning/{i:02d}.mp3"
        if out.exists() and out.stat().st_size > 5000:
            print(f"skip {out.name} already {out.stat().st_size//1024}KB")
            continue
        try:
            await gen_one(t, out)
        except Exception as e:
            print(f"ERR morning {i:02d}: {e}")
        await asyncio.sleep(0.3)
    for i, t in enumerate(evening, 1):
        out = BASE / f"evening/{i:02d}.mp3"
        if out.exists() and out.stat().st_size > 5000:
            print(f"skip {out.name} already {out.stat().st_size//1024}KB")
            continue
        try:
            await gen_one(t, out)
        except Exception as e:
            print(f"ERR evening {i:02d}: {e}")
        await asyncio.sleep(0.3)
    print("done")

asyncio.run(main())
